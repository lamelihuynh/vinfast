require_once __DIR__ . '/../core/lib.php';

$args = bench_args([
    'size'     => '10k',
    'levels'   => '10,1000,10000',
    'products' => 20,
    'warmup'   => 5,
    'runs'     => 30,
]);
bench_require_bench_db($args);

$sizeLabel = (string)$args['size'];
$numProducts = max(1, (int)$args['products']);
$warmup = max(0, (int)$args['warmup']);
$runs = max(1, (int)$args['runs']);
$levels = array_values(array_filter(array_map('intval', explode(',', (string)$args['levels'])), static fn(int $n): bool => $n > 0));
if (!$levels) {
    throw new InvalidArgumentException('Tham số --levels không hợp lệ.');
}

$pdo = Db::pg();
$mongo = Db::mongo();
$embColl = $mongo->selectCollection('bench_reviews_embedded');
$prodColl = $mongo->selectCollection('products');

// Chọn cố định $numProducts sản phẩm đầu tiên từ Mongo products
$targetPids = [];
$origProductSummaries = [];
foreach ($prodColl->find([], ['sort' => ['productID' => 1], 'limit' => $numProducts, 'projection' => ['productID' => 1, 'avgRating' => 1, 'totalReviews' => 1, 'reviews' => 1]]) as $p) {
    $pid = (string)$p['productID'];
    $targetPids[] = $pid;
    $origProductSummaries[$pid] = [
        'avgRating'    => (float)($p['avgRating'] ?? 0.0),
        'totalReviews' => (int)($p['totalReviews'] ?? 0),
        'reviews'      => is_array($p['reviews'] ?? null) ? $p['reviews'] : [],
    ];
}
if (count($targetPids) < $numProducts) {
    throw new RuntimeException("Cần ít nhất {$numProducts} sản phẩm trong MongoDB vinfast_bench.");
}

// Khởi tạo bảng PG bench.product_reviews riêng cho thí nghiệm C
$pdo->exec('CREATE SCHEMA IF NOT EXISTS bench');
$pdo->exec('DROP TABLE IF EXISTS bench.product_reviews CASCADE');
$pdo->exec(<<<'SQL'
CREATE TABLE bench.product_reviews (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     VARCHAR(32)  NOT NULL,
  user_id        BIGINT       NOT NULL,
  user_name      VARCHAR(100) NOT NULL,
  rating         SMALLINT     NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment        TEXT         NOT NULL,
  helpful_count  INTEGER      NOT NULL DEFAULT 0,
  created_at     TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_bench_reviews_prod_created ON bench.product_reviews (product_id, created_at DESC, id DESC);
SQL);

$sampleComments = [
    'Xe vận hành rất êm ái, khả năng tăng tốc mượt và chi phí sạc điện hàng tháng cực kỳ tiết kiệm so với xe xăng trước đây.',
    'Thiết kế nội ngoại thất hiện đại, màn hình giải trí nhạy, hệ thống hỗ trợ lái hoạt động ổn định trên cao tốc.',
    'Dịch vụ hậu mãi tại xưởng VinFast chu đáo, đặt lịch bảo dưỡng nhanh, gia đình mình rất hài lòng sau 6 tháng sử dụng.',
    'Quãng đường di chuyển thực tế sát với công bố, cốp rộng rãi phù hợp đi dã ngoại cuối tuần cùng cả nhà.',
    'Mức giá hợp lý trong phân khúc, pin LFP an toàn, trạm sạc phủ rộng nên đi tỉnh hoàn toàn yên tâm.',
];

/**
 * COPY hàng loạt vào bench.product_reviews.
 * @param array<int, array<int, mixed>> $rows
 */
function copy_bench_reviews(PDO $pdo, array &$rows): void
{
    if (!$rows) {
        return;
    }
    $lines = [];
    foreach ($rows as $r) {
        $cells = [];
        foreach ($r as $v) {
            $cells[] = strtr((string)$v, ["\\" => "\\\\", "\t" => "\\t", "\n" => "\\n", "\r" => "\\r"]);
        }
        $lines[] = implode("\t", $cells);
    }
    $pdo->pgsqlCopyFromArray(
        'bench.product_reviews',
        $lines,
        "\t",
        "\\\\N",
        'id,product_id,user_id,user_name,rating,comment,helpful_count,created_at'
    );
    $rows = [];
}

$csvLatency = "t1_reviews_{$sizeLabel}.csv";
$csvSize = "t1_reviews_size_{$sizeLabel}.csv";
$sizeHeader = ['level', 'product_id', 'bson_bytes', 'pg_bytes_per_product'];

bench_reset_csv($csvLatency, BENCH_RAW_HEADER);
bench_reset_csv($csvSize, $sizeHeader);

$stmtPage1 = $pdo->prepare(
    'SELECT id, user_id, user_name, rating, comment, helpful_count, created_at
       FROM bench.product_reviews
      WHERE product_id = :pid
      ORDER BY created_at DESC, id DESC
      LIMIT 10'
);
$stmtOffsetMid = $pdo->prepare(
    'SELECT id, user_id, user_name, rating, comment, helpful_count, created_at
       FROM bench.product_reviews
      WHERE product_id = :pid
      ORDER BY created_at DESC, id DESC
      LIMIT 10 OFFSET :off'
);
$stmtKeysetMid = $pdo->prepare(
    'SELECT id, user_id, user_name, rating, comment, helpful_count, created_at
       FROM bench.product_reviews
      WHERE product_id = :pid
        AND (created_at, id) < (CAST(:cts AS timestamptz), :cid)
      ORDER BY created_at DESC, id DESC
      LIMIT 10'
);
$stmtCursorLookup = $pdo->prepare(
    'SELECT created_at, id
       FROM bench.product_reviews
      WHERE product_id = :pid
      ORDER BY created_at DESC, id DESC
      LIMIT 1 OFFSET :off'
);
$stmtInsertOne = $pdo->prepare(
    'INSERT INTO bench.product_reviews (product_id, user_id, user_name, rating, comment, helpful_count, created_at)
     VALUES (:pid, :uid, :uname, :rating, :comment, 0, now())
     RETURNING id'
);
$stmtDeleteOne = $pdo->prepare('DELETE FROM bench.product_reviews WHERE id = :id');
$stmtAvg = $pdo->prepare('SELECT count(*) AS n, avg(rating) AS avg_r FROM bench.product_reviews WHERE product_id = :pid');

$avgBsonByLevel = [];

try {
    foreach ($levels as $level) {
        mt_srand(42 + $level);
        printf("\n=== Experiment C — Level = %d reviews/product (%d products) ===\n", $level, $numProducts);

        // 1. Dựng dữ liệu sạch cho mức $level ở cả Mongo (embedded + hybrid) và PG
        $embColl->drop();
        $embColl->createIndex(['productID' => 1], ['unique' => true, 'name' => 'uq_bench_rev_pid']);

        $pdo->beginTransaction();
        $pdo->exec('TRUNCATE bench.product_reviews RESTART IDENTITY');

        $baseTs = 1760000000;
        $nextId = 1;
        $pgBatch = [];

        foreach ($targetPids as $pIdx => $pid) {
            $embColl->insertOne(['productID' => $pid, 'reviews' => []]);

            $mongoChunk = [];
            $top5 = [];
            $ratingSum = 0;

            // Sinh từ mới nhất (j = 0) về cũ nhất (j = $level - 1) để đầu mảng Mongo luôn là mới nhất
            for ($j = 0; $j < $level; $j++) {
                $rid = $nextId++;
                $uid = ($j % 500) + 1;
                $uname = 'Khách hàng #' . $uid;
                $rating = [5, 5, 4, 4, 3, 5, 4, 2, 5, 1][$j % 10];
                $ratingSum += $rating;
                $comment = $sampleComments[$j % count($sampleComments)] . " (#{$j})";
                $helpful = $j % 15;
                $tsSec = $baseTs - ($j * 60) - $pIdx;

                $revDoc = [
                    'reviewId'         => $rid,
                    'userId'           => $uid,
                    'userNameSnapshot' => $uname,
                    'rating'           => $rating,
                    'comment'          => $comment,
                    'images'           => [],
                    'createdAt'        => new MongoDB\BSON\UTCDateTime($tsSec * 1000),
                    'helpfulCount'     => $helpful,
                ];
                $mongoChunk[] = $revDoc;
                if (count($top5) < 5) {
                    $top5[] = $revDoc;
                }

                // Chia lô $push + $each mỗi 1000 phần tử để không chạm trần lệnh BSON
                if (count($mongoChunk) >= 1000) {
                    $embColl->updateOne(
                        ['productID' => $pid],
                        ['$push' => ['reviews' => ['$each' => $mongoChunk]]]
                    );
                    $mongoChunk = [];
                }

                $pgBatch[] = [
                    $rid,
                    $pid,
                    $uid,
                    $uname,
                    $rating,
                    $comment,
                    $helpful,
                    date('Y-m-d H:i:sP', $tsSec),
                ];
                if (count($pgBatch) >= 5000) {
                    copy_bench_reviews($pdo, $pgBatch);
                }
            }

            if ($mongoChunk) {
                $embColl->updateOne(
                    ['productID' => $pid],
                    ['$push' => ['reviews' => ['$each' => $mongoChunk]]]
                );
            }

            // Đồng bộ tóm tắt 5 bài cho biến thể hybrid_page1 trên collection `products`
            $prodColl->updateOne(
                ['productID' => $pid],
                ['$set' => [
                    'avgRating'    => round($ratingSum / $level, 2),
                    'totalReviews' => $level,
                    'reviews'      => $top5,
                ]]
            );
        }

        copy_bench_reviews($pdo, $pgBatch);
        $pdo->query("SELECT setval(pg_get_serial_sequence('bench.product_reviews', 'id'), (SELECT max(id) FROM bench.product_reviews) + 1, false)");
        $pdo->commit();
        $pdo->exec('VACUUM ANALYZE bench.product_reviews');

        // Kiểm tra tính đúng đắn của số phần tử / số dòng vừa nạp
        $checkDocCount = (int)($embColl->aggregate([
            ['$match' => ['productID' => $targetPids[0]]],
            ['$project' => ['n' => ['$size' => '$reviews']]],
        ])->toArray()[0]['n'] ?? 0);
        $checkPgRows = (int)$pdo->query('SELECT count(*) FROM bench.product_reviews')->fetchColumn();
        if ($checkDocCount !== $level || $checkPgRows !== $numProducts * $level) {
            throw new RuntimeException("Sai số lượng nạp ở level {$level}: mongo={$checkDocCount}, pg={$checkPgRows}");
        }

        // Chuẩn bị dãy 35 sản phẩm truy vấn và con trỏ keyset tại giữa danh sách ($midOffset)
        $midOffset = max(1, intdiv($level, 2));
        $midCursors = [];
        foreach ($targetPids as $pid) {
            $stmtCursorLookup->bindValue(':pid', $pid, PDO::PARAM_STR);
            $stmtCursorLookup->bindValue(':off', $midOffset - 1, PDO::PARAM_INT);
            $stmtCursorLookup->execute();
            $midCursors[$pid] = $stmtCursorLookup->fetch(PDO::FETCH_ASSOC);
        }

        $totalCalls = $warmup + $runs;
        $pickSeq = [];
        for ($i = 0; $i < $totalCalls; $i++) {
            $pickSeq[] = $targetPids[mt_rand(0, count($targetPids) - 1)];
        }

        $ops = [
            'embedded_read_page1' => [
                'db'  => 'mongo',
                'run' => static function (string $pid) use ($embColl): array {
                    $doc = $embColl->findOne(
                        ['productID' => $pid],
                        ['projection' => ['_id' => 0, 'reviews' => ['$slice' => [0, 10]]]]
                    );
                    $revs = is_array($doc['reviews'] ?? null) ? $doc['reviews'] : [];
                    return ['rows' => count($revs), 'raw' => $revs, 'cleanup' => null];
                },
            ],
            'sql_read_page1' => [
                'db'  => 'postgres',
                'run' => static function (string $pid) use ($stmtPage1): array {
                    $stmtPage1->execute([':pid' => $pid]);
                    $rows = $stmtPage1->fetchAll(PDO::FETCH_ASSOC);
                    return ['rows' => count($rows), 'raw' => $rows, 'cleanup' => null];
                },
            ],
            'hybrid_page1' => [
                'db'  => 'mongo',
                'run' => static function (string $pid) use ($prodColl): array {
                    $doc = $prodColl->findOne(
                        ['productID' => $pid],
                        ['projection' => ['_id' => 0, 'avgRating' => 1, 'totalReviews' => 1, 'reviews' => 1]]
                    );
                    $revs = is_array($doc['reviews'] ?? null) ? $doc['reviews'] : [];
                    return ['rows' => count($revs), 'raw' => $doc, 'cleanup' => null];
                },
            ],
            'embedded_read_mid' => [
                'db'  => 'mongo',
                'run' => static function (string $pid) use ($embColl, $midOffset): array {
                    $doc = $embColl->findOne(
                        ['productID' => $pid],
                        ['projection' => ['_id' => 0, 'reviews' => ['$slice' => [$midOffset, 10]]]]
                    );
                    $revs = is_array($doc['reviews'] ?? null) ? $doc['reviews'] : [];
                    return ['rows' => count($revs), 'raw' => $revs, 'cleanup' => null];
                },
            ],
            'sql_offset_mid' => [
                'db'  => 'postgres',
                'run' => static function (string $pid) use ($stmtOffsetMid, $midOffset): array {
                    $stmtOffsetMid->bindValue(':pid', $pid, PDO::PARAM_STR);
                    $stmtOffsetMid->bindValue(':off', $midOffset, PDO::PARAM_INT);
                    $stmtOffsetMid->execute();
                    $rows = $stmtOffsetMid->fetchAll(PDO::FETCH_ASSOC);
                    return ['rows' => count($rows), 'raw' => $rows, 'cleanup' => null];
                },
            ],
            'sql_keyset_mid' => [
                'db'  => 'postgres',
                'run' => static function (string $pid) use ($stmtKeysetMid, $midCursors): array {
                    $cur = $midCursors[$pid];
                    $stmtKeysetMid->bindValue(':pid', $pid, PDO::PARAM_STR);
                    $stmtKeysetMid->bindValue(':cts', (string)$cur['created_at'], PDO::PARAM_STR);
                    $stmtKeysetMid->bindValue(':cid', (int)$cur['id'], PDO::PARAM_INT);
                    $stmtKeysetMid->execute();
                    $rows = $stmtKeysetMid->fetchAll(PDO::FETCH_ASSOC);
                    return ['rows' => count($rows), 'raw' => $rows, 'cleanup' => null];
                },
            ],
            'embedded_write_one' => [
                'db'  => 'mongo',
                'run' => static function (string $pid) use ($embColl): array {
                    $newDoc = [
                        'reviewId'         => 99999999,
                        'userId'           => 1,
                        'userNameSnapshot' => 'Khách hàng mới',
                        'rating'           => 5,
                        'comment'          => 'Đánh giá mới chèn vào đầu mảng để đo chi phí ghi lại document.',
                        'images'           => [],
                        'createdAt'        => new MongoDB\BSON\UTCDateTime(),
                        'helpfulCount'     => 0,
                    ];
                    $embColl->updateOne(
                        ['productID' => $pid],
                        ['$push' => ['reviews' => ['$each' => [$newDoc], '$position' => 0]]]
                    );
                    return [
                        'rows'    => 1,
                        'bytes'   => 180,
                        'cleanup' => static function () use ($embColl, $pid): void {
                            $embColl->updateOne(['productID' => $pid], ['$pop' => ['reviews' => -1]]);
                        },
                    ];
                },
            ],
            'sql_write_one' => [
                'db'  => 'postgres',
                'run' => static function (string $pid) use ($stmtInsertOne, $stmtDeleteOne): array {
                    $stmtInsertOne->execute([
                        ':pid'     => $pid,
                        ':uid'     => 1,
                        ':uname'   => 'Khách hàng mới',
                        ':rating'  => 5,
                        ':comment' => 'Đánh giá mới chèn vào bảng SQL độc lập.',
                    ]);
                    $newId = (int)$stmtInsertOne->fetchColumn();
                    return [
                        'rows'    => 1,
                        'bytes'   => 180,
                        'cleanup' => static function () use ($stmtDeleteOne, $newId): void {
                            $stmtDeleteOne->execute([':id' => $newId]);
                        },
                    ];
                },
            ],
            'embedded_avg' => [
                'db'  => 'mongo',
                'run' => static function (string $pid) use ($embColl): array {
                    $res = $embColl->aggregate([
                        ['$match' => ['productID' => $pid]],
                        ['$project' => ['_id' => 0, 'n' => ['$size' => '$reviews'], 'avg' => ['$avg' => '$reviews.rating']]],
                    ])->toArray();
                    return ['rows' => 1, 'raw' => $res, 'cleanup' => null];
                },
            ],
            'sql_avg' => [
                'db'  => 'postgres',
                'run' => static function (string $pid) use ($stmtAvg): array {
                    $stmtAvg->execute([':pid' => $pid]);
                    $row = $stmtAvg->fetch(PDO::FETCH_ASSOC);
                    return ['rows' => 1, 'raw' => $row, 'cleanup' => null];
                },
            ],
        ];

        echo str_repeat('-', 72) . PHP_EOL;
        printf("%-22s | %10s | %10s | %10s | %8s\n", 'Variant (L=' . $level . ')', 'p50 (ms)', 'p95 (ms)', 'max (ms)', 'Rows');
        echo str_repeat('-', 72) . PHP_EOL;

        foreach ($ops as $vName => $cfg) {
            $fn = $cfg['run'];

            for ($w = 0; $w < $warmup; $w++) {
                $r = $fn($pickSeq[$w]);
                if ($r['cleanup'] !== null) {
                    ($r['cleanup'])();
                }
            }

            $latencies = [];
            $lastRows = 0;
            for ($run = 1; $run <= $runs; $run++) {
                $pid = $pickSeq[$warmup + $run - 1];
                $res = null;
                $ms = bench_time(static function () use ($fn, $pid, &$res): void {
                    $res = $fn($pid);
                });
                if ($res['cleanup'] !== null) {
                    ($res['cleanup'])();
                }
                // Thao tác ghi khai báo sẵn 'bytes'; thao tác đọc trả 'raw', đếm byte ngoài đoạn bấm giờ
                $bytes = $res['bytes'] ?? bench_payload_bytes($res['raw'] ?? null);

                $latencies[] = $ms;
                $lastRows = $res['rows'];

                bench_csv($csvLatency, BENCH_RAW_HEADER, [
                    'reviews',
                    $cfg['db'],
                    $vName,
                    $sizeLabel,
                    $level,
                    $run,
                    sprintf('%.4f', $ms),
                    $res['rows'],
                    $bytes,
                    bench_now_iso(),
                ]);
            }

            printf(
                "%-22s | %10.3f | %10.3f | %10.3f | %8d\n",
                $vName,
                bench_percentile($latencies, 50),
                bench_percentile($latencies, 95),
                max($latencies),
                $lastRows
            );
        }

        // Đo kích thước lưu trữ chính xác sau khi thu dọn tuple nháp
        $pdo->exec('VACUUM FULL bench.product_reviews');
        $pgTotalBytes = (int)$pdo->query("SELECT pg_total_relation_size('bench.product_reviews')")->fetchColumn();
        $pgBytesPerProduct = (int)round($pgTotalBytes / $numProducts);

        $sizeDocs = $embColl->aggregate([
            ['$project' => ['_id' => 0, 'productID' => 1, 'n' => ['$size' => '$reviews'], 'bytes' => ['$bsonSize' => '$$ROOT']]],
            ['$sort' => ['productID' => 1]],
        ])->toArray();

        $bsonSum = 0;
        foreach ($sizeDocs as $sd) {
            if ((int)$sd['n'] !== $level) {
                throw new RuntimeException("Sau khi chạy đo, số review của {$sd['productID']} bị lệch: {$sd['n']} != {$level}");
            }
            $b = (int)$sd['bytes'];
            $bsonSum += $b;
            bench_csv($csvSize, $sizeHeader, [
                $level,
                (string)$sd['productID'],
                $b,
                $pgBytesPerProduct,
            ]);
        }
        $avgBson = $bsonSum / count($sizeDocs);
        $avgBsonByLevel[$level] = $avgBson;

        printf(
            "Storage @ level=%d: avg BSON doc = %.1f KB (%.3f MB), PG relation/product = %.1f KB\n",
            $level,
            $avgBson / 1024,
            $avgBson / (1024 * 1024),
            $pgBytesPerProduct / 1024
        );
    }

    // Ngoại suy ngưỡng chạm trần 16 MB BSON (16,777,216 bytes)
    if (count($avgBsonByLevel) >= 2) {
        $lvKeys = array_keys($avgBsonByLevel);
        $minLv = min($lvKeys);
        $maxLv = max($lvKeys);
        $bytesPerReview = ($avgBsonByLevel[$maxLv] - $avgBsonByLevel[$minLv]) / ($maxLv - $minLv);
        $baseOverhead = $avgBsonByLevel[$minLv] - $bytesPerReview * $minLv;
        $limit16Mb = 16 * 1024 * 1024;
        $maxReviewsBefore16Mb = (int)floor(($limit16Mb - $baseOverhead) / $bytesPerReview);
        printf(
            "\nExtrapolation -> ~%.1f bytes/review => chạm trần 16 MB BSON tại khoảng %s reviews/sản phẩm.\n",
            $bytesPerReview,
            number_format($maxReviewsBefore16Mb, 0, ',', '.')
        );
    }
} finally {
    // Khôi phục lại tóm tắt review gốc của 20 sản phẩm trong vinfast_bench.products
    foreach ($origProductSummaries as $pid => $orig) {
        $prodColl->updateOne(['productID' => $pid], ['$set' => $orig]);
    }
}

printf("Saved CSVs -> bench/t1/results/raw/%s & bench/t1/results/raw/%s\n", $csvLatency, $csvSize);
