<?php

/**
 * bench/t1/experiments/reviews.php — Thí nghiệm C: Review nhúng toàn bộ vs Bảng SQL vs Phương án Lai (T1-21)
 *
 * Chạy trên DB `vinfast_bench` (seed 10k):
 *   docker compose exec -e PG_DB=vinfast_bench -e MONGO_DB=vinfast_bench app \
 *     php bench/t1/experiments/reviews.php --levels=10,1000,10000 --products=20 --warmup=5 --runs=30
