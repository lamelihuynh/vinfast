-- =============================================================================
-- VinFast hybrid DB — Coupon (quyết định 11). Chủ file: T4 (Transaction).
-- Chạy sau 001_schema.sql. Luồng dùng (CouponService):
--   1. quote(): đọc coupon, kiểm tra hạn + min_order_amount, tính discount_amount
--   2. INSERT orders (... coupon_id, discount_amount, total_amount ...)
--   3. Sau bước trừ kho, giữ quota bằng UPDATE có điều kiện:
--        UPDATE coupons SET used_count = used_count + 1
--        WHERE id = :id AND is_active AND now() BETWEEN starts_at AND expires_at
--          AND (usage_limit IS NULL OR used_count < usage_limit)
--      0 dòng bị ảnh hưởng -> rollback toàn bộ đơn.
--   4. INSERT coupon_redemptions (UNIQUE chặn 1 user dùng 1 coupon 2 lần).
-- =============================================================================

BEGIN;

CREATE TABLE coupons (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              VARCHAR(40)   NOT NULL,
  description       VARCHAR(255),
  discount_type     VARCHAR(10)   NOT NULL CHECK (discount_type IN ('percent', 'fixed')),
  discount_value    NUMERIC(15,0) NOT NULL CHECK (discount_value > 0),
  max_discount      NUMERIC(15,0) CHECK (max_discount > 0),          -- trần cho loại percent
  min_order_amount  NUMERIC(15,0) NOT NULL DEFAULT 0 CHECK (min_order_amount >= 0),
  usage_limit       INTEGER       CHECK (usage_limit > 0),            -- NULL = không giới hạn
  used_count        INTEGER       NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  per_user_limit    INTEGER       NOT NULL DEFAULT 1 CHECK (per_user_limit > 0),
  starts_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
  expires_at        TIMESTAMPTZ   NOT NULL,
  is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
  created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT ck_coupon_percent CHECK (discount_type <> 'percent' OR discount_value <= 100),
  CONSTRAINT ck_coupon_window  CHECK (expires_at > starts_at),
  CONSTRAINT ck_coupon_quota   CHECK (usage_limit IS NULL OR used_count <= usage_limit)
);
CREATE UNIQUE INDEX uq_coupons_code_upper ON coupons (upper(code));

CREATE TRIGGER trg_coupons_updated_at BEFORE UPDATE ON coupons
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE coupon_redemptions (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coupon_id        BIGINT        NOT NULL REFERENCES coupons (id) ON DELETE RESTRICT,
  user_id          BIGINT        NOT NULL REFERENCES users (id)   ON DELETE RESTRICT,
  order_id         BIGINT        NOT NULL UNIQUE REFERENCES orders (id) ON DELETE CASCADE,
  discount_amount  NUMERIC(15,0) NOT NULL CHECK (discount_amount >= 0),
  redeemed_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- per_user_limit = 1 mặc định; nếu cần >1 thì bỏ UNIQUE này và đếm trong CouponService.
CREATE UNIQUE INDEX uq_coupon_redemption_user ON coupon_redemptions (coupon_id, user_id);

ALTER TABLE orders
  ADD CONSTRAINT fk_orders_coupon FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE RESTRICT;
CREATE INDEX idx_orders_coupon ON orders (coupon_id) WHERE coupon_id IS NOT NULL;

COMMIT;
